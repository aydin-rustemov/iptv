#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
M3U / M3U8 Playlist Builder.
Generates IPTV-standard playlists with full metadata, group tags, and player directives.
"""

from datetime import datetime
from typing import List, Dict

class M3UBuilder:
    @staticmethod
    def build_playlist(channels: List[Dict], title: str = "Live TV Playlist") -> str:
        """
        Builds a full M3U playlist string from a list of validated channel objects.
        """
        timestamp = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
        lines = [
            "#EXTM3U",
            f'# Generated by Automated IPTV Orchestrator ({timestamp})',
            f'# Total Active Channels: {len(channels)}'
        ]

        for ch in channels:
            # Metadata attributes
            cid = ch.get("id", ch.get("name", ""))
            name = ch.get("name", "Unknown Channel")
            group = ch.get("group", "General")
            logo = ch.get("logo", "")
            stream_url = ch.get("url", "")
            headers = ch.get("headers", {})

            extinf = f'#EXTINF:-1 tvg-id="{cid}" tvg-name="{name}" group-title="{group}"'
            if logo:
                extinf += f' tvg-logo="{logo}"'
            extinf += f',{name}'

            lines.append(extinf)

            # Add Player HTTP directives for anti-hotlink bypass
            if headers:
                if "User-Agent" in headers:
                    lines.append(f'#EXTVLCOPT:http-user-agent={headers["User-Agent"]}')
                if "Referer" in headers:
                    lines.append(f'#EXTVLCOPT:http-referrer={headers["Referer"]}')
                    lines.append(f'#EXTHTTP:{{"Referer":"{headers["Referer"]}"}}')

            lines.append(stream_url)

        return "\n".join(lines) + "\n"

    @staticmethod
    def save_playlist(filepath: str, channels: List[Dict], title: str = "IPTV") -> None:
        """
        Saves the formatted playlist directly to a file with UTF-8 encoding.
        """
        content = M3UBuilder.build_playlist(channels, title)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)
